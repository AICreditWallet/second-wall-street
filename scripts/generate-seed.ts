/**
 * Writes supabase/seed.sql from the deterministic city generator.
 * Run: npm run db:seed:generate
 * The database is the source of truth after the first deploy; re-running this
 * only matters for fresh environments (local, staging).
 */
import { writeFileSync } from "node:fs";
import { generateCity } from "../src/lib/city/generator";
import { PLATFORM_ORG_UUIDS } from "../src/lib/city/organizations";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const city = generateCity();
const lines: string[] = ["-- Generated by scripts/generate-seed.ts — do not edit by hand.", "begin;"];

city.districts.forEach((d, i) =>
  lines.push(
    `insert into public.districts (id, slug, name, tagline, center_x, center_z, sort_order) values (${q(d.id)}, ${q(d.slug)}, ${q(d.name)}, ${q(d.tagline)}, ${d.center[0]}, ${d.center[1]}, ${i}) on conflict (id) do nothing;`,
  ),
);
for (const b of city.buildings) {
  lines.push(
    `insert into public.buildings (id, district_id, name, address, pos_x, pos_z, width, depth, height, floors, shape, color, window_style, tier) values (${q(b.id)}, ${q(b.districtId)}, ${q(b.name)}, ${q(b.address)}, ${b.position[0]}, ${b.position[1]}, ${b.footprint[0]}, ${b.footprint[1]}, ${b.height}, ${b.floors}, ${q(b.shape)}, ${q(b.color)}, ${q(b.windowStyle)}, ${q(b.tier)}) on conflict (id) do nothing;`,
  );
}
for (const o of city.organizations) {
  const uuid = PLATFORM_ORG_UUIDS[o.id];
  lines.push(
    `insert into public.organizations (id, slug, name, tagline, description, website_url, operator, verified, is_demo) values (${q(uuid)}, ${q(o.slug)}, ${q(o.name)}, ${q(o.tagline)}, ${q(o.description)}, ${q(o.website ?? null)}, 'platform', ${o.verified}, ${o.isDemo}) on conflict (id) do nothing;`,
  );
}
for (const o of city.offices) {
  const org = o.organizationId ? PLATFORM_ORG_UUIDS[o.organizationId] : null;
  lines.push(
    `insert into public.offices (id, building_id, label, tier, status, organization_id) values (${q(o.id)}, ${q(o.buildingId)}, ${q(o.label)}, ${q(o.tier)}, ${q(o.status)}, ${q(org)}) on conflict (id) do nothing;`,
  );
}
for (const a of city.agents) {
  const org = PLATFORM_ORG_UUIDS[a.organizationId];
  const caps = `array[${a.capabilities.map(q).join(", ")}]::text[]`;
  lines.push(
    `insert into public.agents (id, slug, organization_id, name, category, summary, capabilities, status, disclosure, published) values (${q(a.id)}, ${q(a.slug)}, ${q(org)}, ${q(a.name)}, ${q(a.category)}, ${q(a.summary)}, ${caps}, ${q(a.status)}, ${q(a.disclosure ?? null)}, true) on conflict (id) do nothing;`,
  );
}
lines.push(
  `insert into public.office_plans (id, tier, name, description, active) values
  ('standard', 'standard', 'Standard office', 'Free office for every verified developer.', true),
  ('premium', 'premium', 'Premium office', 'High-visibility location. Pricing to be approved.', false),
  ('landmark', 'landmark', 'Landmark office', 'Signature tower location. Pricing to be approved.', false)
  on conflict (id) do nothing;`,
);
lines.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(`seed.sql: ${city.buildings.length} buildings, ${city.offices.length} offices`);
