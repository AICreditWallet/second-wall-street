/**
 * Writes supabase/repairs/20261101_fix_text_encoding.sql: restores the exact
 * seeded text (labels, descriptions) whose non-ASCII characters were garbled
 * when the seed was first pasted without UTF-8 encoding. Text fields only —
 * never status, ownership or community data. Idempotent.
 */
import { writeFileSync } from "node:fs";
import { generateCity } from "../src/lib/city/generator";
import { PLATFORM_ORG_UUIDS } from "../src/lib/city/organizations";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const city = generateCity();
const out: string[] = ["-- Generated by scripts/generate-encoding-repair.ts. Safe to run more than once.", "begin;"];

for (const o of city.offices) out.push(`update public.offices set label = ${q(o.label)} where id = ${q(o.id)} and label is distinct from ${q(o.label)};`);
for (const b of city.buildings)
  out.push(`update public.buildings set name = ${q(b.name)}, address = ${q(b.address)} where id = ${q(b.id)} and (name, address) is distinct from (${q(b.name)}, ${q(b.address)});`);
for (const d of city.districts) out.push(`update public.districts set name = ${q(d.name)}, tagline = ${q(d.tagline)} where id = ${q(d.id)};`);
for (const o of city.organizations)
  out.push(`update public.organizations set name = ${q(o.name)}, tagline = ${q(o.tagline)}, description = ${q(o.description)} where id = ${q(PLATFORM_ORG_UUIDS[o.id])} and operator = 'platform';`);
for (const a of city.agents)
  out.push(`update public.agents set name = ${q(a.name)}, category = ${q(a.category)}, summary = ${q(a.summary)}, disclosure = ${q(a.disclosure ?? null)} where id = ${q(a.id)};`);
out.push(
  "-- Verify: should return 0",
  "select (select count(*) from public.offices where label !~ '^Floors? [0-9]+(–[0-9]+)?$') + (select count(*) from public.organizations where description like '%‚Ä%') + (select count(*) from public.agents where summary like '%‚Ä%') as still_garbled;",
  "commit;",
  "",
);
writeFileSync(new URL("../supabase/repairs/20261101_fix_text_encoding.sql", import.meta.url), out.join("\n"));
console.log(`${out.length} lines`);
